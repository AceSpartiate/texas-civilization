import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createClassroom } from '../server/app.mjs';
import { createWorld } from '../sim/world.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const app = createClassroom({ seed: 'trade-animation-proof', playerCount: 5, tickMs: 250, worldFactory(seed, count) {
  const world = createWorld(seed, count), home = world.map.sites['home-1'];
  world.entities['hh-2-elena'].location = { x: home.x + .35, y: home.y + .12, siteId: home.id };
  world.households['hh-1'].resources.food = 30;
  world.households['hh-1'].resources.seed = 12;
  return world;
} });
const port = await app.listen(0, '127.0.0.1'), url = `http://127.0.0.1:${port}`;
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE && { executablePath: process.env.BROWSER_EXECUTABLE }) });
const errors = [];
const post = async (path, body, cookie) => {
  const response = await fetch(url + path, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(cookie && { Cookie: cookie }) }, body: JSON.stringify(body) });
  assert.equal(response.status, 200, `${path}: ${response.status}`);
  return response;
};
try {
  const host = await post('/api/host', { key: app.state.hostKey });
  const hostCookie = host.headers.get('set-cookie').split(';')[0];
  const command = action => post('/api/command', { id: `proof-${action}-${crypto.randomUUID()}`, action }, hostCookie);
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.locator('[name=name]').fill('Trade reader');
  await page.locator('[name=code]').fill(app.state.sessionCode);
  await page.getByRole('button', { name: 'Join', exact: true }).click();
  await page.waitForFunction(() => window.__snapshot?.world.householdId === 'hh-1');
  for (let i = 2; i <= 5; i++) await post('/api/join', { name: `Reader ${i}`, code: app.state.sessionCode });
  await command('start');
  await page.waitForFunction(() => window.__snapshot?.world.status === 'running' && window.__animation?.timeMs > 500);
  const choose = async id => {
    await page.locator('#journal-toggle').click();
    await page.locator(`[data-select="${id}"]`).click();
    await page.locator('#journal-close').click();
    await page.locator('#selection').waitFor({ state: 'visible' });
  };
  await choose('hh-2-elena');
  await page.locator('#trade-from').selectOption('hh-1-elena');
  await page.locator('#trade-give-good').selectOption('food');
  await page.locator('#trade-ask-good').selectOption('seed');
  await page.locator('#trade-give-amount').fill('7');
  await page.locator('#trade-ask-amount').fill('3');
  await page.locator('#trade-give-amount').focus();
  await page.evaluate(() => { window.__tradeInputBefore = document.querySelector('#trade-give-amount'); });
  const firstTick = await page.evaluate(() => window.__snapshot.world.tick);
  await page.waitForFunction(tick => window.__snapshot.world.tick >= tick + 4, firstTick);
  assert.equal(await page.locator('#trade-give-amount').inputValue(), '7');
  assert.equal(await page.locator('#trade-from').inputValue(), 'hh-1-elena');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'trade-give-amount');
  assert.equal(await page.evaluate(() => window.__tradeInputBefore === document.querySelector('#trade-give-amount')), true, 'animation and unchanged snapshots retain the actual input node');
  await command('pause');
  await page.waitForFunction(() => window.__snapshot.world.status === 'paused');
  assert.equal(await page.locator('#trade-give-amount').inputValue(), '7', 'draft survives a meaningful authoritative rebuild');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'trade-give-amount', 'focus survives a meaningful authoritative rebuild');
  assert.equal(await page.locator('#trade-ask-amount').inputValue(), '3');
  await command('resume');
  await page.waitForFunction(() => window.__snapshot.world.status === 'running');
  assert.equal(await page.locator('#trade-give-good').inputValue(), 'food');
  assert.equal(await page.locator('#trade-ask-good').inputValue(), 'seed');
  await page.locator('[data-action="offer"]').click();
  await page.waitForFunction(() => window.__snapshot.world.offers.length === 1);
  const offer = Object.values(app.state.world.offers)[0];
  assert.deepEqual(offer.give, { food: 7 });
  assert.deepEqual(offer.ask, { seed: 3 });
  assert.equal(offer.fromEntityId, 'hh-1-elena');
  assert.equal(offer.toEntityId, 'hh-2-elena');
  await choose('hh-1-thomas');
  const work = page.locator('[data-chore="plant-field"]');
  await work.focus();
  await page.evaluate(() => { window.__workBefore = document.activeElement; });
  const workTick = await page.evaluate(() => window.__snapshot.world.tick);
  await page.waitForFunction(tick => window.__snapshot.world.tick >= tick + 4, workTick);
  assert.equal(await page.evaluate(() => document.activeElement === window.__workBefore && document.activeElement.dataset.chore === 'plant-field'), true, 'work controls retain keyboard focus while animation and snapshots continue');
  assert.deepEqual(errors, []);
  const evidence = { result: 'PASS', date: new Date().toISOString(), browser: await browser.version(), animationAndSnapshotsRetainInputNode: true, draftAndFocusSurvivePauseResume: true, chosenTradeReachedServer: { from: offer.fromEntityId, to: offer.toEntityId, give: offer.give, ask: offer.ask }, workFocusPreserved: true, errors };
  mkdirSync('docs/evidence', { recursive: true });
  writeFileSync('docs/evidence/trade-animation.json', JSON.stringify(evidence, null, 2) + '\n');
  console.log(JSON.stringify(evidence, null, 2));
} finally { await browser.close(); await app.close(); }
