// ---------------------------------------------------------------------------------------------------------------- E3
// One roof over a two-pen house. Her roof is a gable roof on a ridge: moved along its ridge by any distance, its boards,
// poles and ridge log land on themselves. So the section between two pens is her roof's middle band - clear of both gable
// ends, their end poles, the ridge log's cut ends and the posts under the front gable - laid again and again along the
// ridge, each copy cut to the next band. The bands' edges run down the right slope along a board joint, so a seam is a
// joint. The section spans the same stretch of ridge as her whole roof (a pen's depth, sixteen feet) in the same box, so it
// seats on the walls exactly as her roof does, and laid over the gap between two pens it runs into both roofs.
//
// `STEP` is one band along the ridge in her roof's pixels, whole pixels so no copy is resampled: the ridge's direction read
// by self-similarity of the roof's middle (40 across, 33-34 up) at about one clapboard's width.
const JOIN = {
  'house-roof-join': { from: 'house-hewn-roof-finished' },
  'house-roof-join-partial': { from: 'house-round-roof-partial' },
};
const STEP = [18, -15];
/** The joint direction on the right slope (down it, toward the eave), along which the bands are cut. */
const JOINT_DIR = [0.62, 0.785];
/** Room round her roof's box: the section's front eave runs a little past where her gable's corner was. */
const MARGIN = 24;

/**
 * The ridge of her roof as a line in its frame's pixels: RIDGE in public/house-plot.js, read off the finished roof's ridge
 * log (it serves the partial roof within a degree). Kept here as data so the join frames carry their own ridge.
 */
const HER_RIDGE = [[110, 96], [205, 12]];

function roofJoin(name, { hole, span, under, over, bottom = 0 } = {}) {
  const spec = JOIN[name] || JOIN['house-roof-join'], frame = her(spec.from), m = MARGIN;
  const c = new Canvas(name, frame.w + 2 * m, frame.h + 2 * m + bottom);
  // p = origin + s * STEP + t * JOINT_DIR: s counts bands along the ridge, t pixels down the joints.
  const [ux, uy] = STEP, [jx, jy] = JOINT_DIR, det = ux * jy - uy * jx;
  const origin = [HER_RIDGE[0][0] + m, HER_RIDGE[0][1] + m];
  const s1 = ((HER_RIDGE[1][0] - HER_RIDGE[0][0]) * jy - (HER_RIDGE[1][1] - HER_RIDGE[0][1]) * jx) / det; // her ridge, in bands
  const bandFrom = Math.round(s1 * 0.4); // band 0: plain roof, clear of both gables' clutter
  const point = (s, t) => [origin[0] + s * ux + t * jx, origin[1] + s * uy + t * jy];
  const T0 = -260, T1 = 320; // far enough across to take the whole roof, both slopes and the eave blocks under it
  // The section's own ends: her roof's ridge with its overhang, or a share of it (`span`).
  const [S_LO, S_HI] = span ? [s1 * span[0], s1 * span[1]] : [-0.5, s1 + 0.5];
  if (under) under(c, point, S_LO, S_HI);
  const mask = hole ? hole(c, point) : null;
  const group = [];
  for (let k = -12; k <= 12; k++) {
    const lo = Math.max(S_LO, bandFrom + k), hi = Math.min(S_HI, bandFrom + k + 1);
    if (hi <= lo) continue;
    // Band 0's pixels moved k bands along the ridge; the cut edges overlap a hair so no gap opens between copies.
    const clip = c.clip([point(lo - 0.02, T0), point(hi + 0.02, T0), point(hi + 0.02, T1), point(lo - 0.02, T1)]);
    group.push(`<g clip-path="url(#${clip})">${c.image(frame, m, m, { transform: `translate(${k * ux} ${k * uy})` })}</g>`);
  }
  c.raw(`<g${mask ? ` mask="url(#${mask})"` : ''}>${group.join('')}</g>`);
  if (over) over(c, point, S_LO, S_HI);
  const fx = x => +(x / c.w).toFixed(4), fy = y => +(y / c.h).toFixed(4);
  const ridge = [point(S_LO, 0), point(S_HI, 0)].map(([x, y]) => [fx(x), fy(y)]);
  return {
    c, point, frame, m,
    svg: c.svg(`the middle of Astra's ${spec.from} repeated along its ridge: one roof section with no gable end and no end pole, to lie between two pens`),
    anchorX: fx(frame.anchorX * frame.w + m), anchorY: fy(frame.anchorY * frame.h + m), logicalHeight: frame.h,
    seat: [fx(frame.seatX * frame.w + m), fy(frame.seatY * frame.h + m)], extra: { ridge },
  };
}

const joinFrames = cell => Object.keys(JOIN).map(name => ({
  name, draw: () => roofJoin(name), height: 1.9, cell,
  compare: [[JOIN[name].from, 1.9], ['house-passage-roof', 1.9], ['rust-idle-s', 1]],
  prompt: `The clapboard roof over the open passage between two ${name.endsWith('partial') ? 'still-unchinked ' : ''}log pens, as one run of roof with them: Astra's ${JOIN[name].from} with both gable ends, the end poles, the ridge log's cut ends and the posts under the gable taken away, its middle - boards running from ridge to eave, the weight poles and the ridge log running through - repeated along the ridge (her pixels moved along the ridge, which maps a gable roof onto itself) over the same sixteen feet of ridge as her roof, so seated on a pen's walls as her roof is it covers the passage and runs into both pens' roofs without a seam. Exactly her pitch, ridge, eaves, scale and outline; the ridge line is given with the frame (\`ridge\`). Corner-on three-quarter view, transparent ground.`,
}));

// ---------------------------------------------------------------------------------------------------------------- the pen's projection
// New pieces are built in feet and projected as her pen is drawn. Her round full walls stand corner-on on a sixteen-foot
// square: the feet of the left, front and right corner posts are measured (`ground`, scripts/build-atlas-manifest.mjs) at
// (4.5, 195), (182.5, 250) and (297.5, 167) of her frame, so a foot along the door's face (a, left to front) is A and a foot
// along the long side (b, front to right, the way the ridge runs) is B. Up is 13 pixels a foot: her doorway is about 78
// pixels high and a door about six feet; her walls, 123 pixels at the front corner, are then about nine and a half feet.
// ceiling: an affine reading of a hand-drawn picture - her roof's ridge runs steeper than B (RIDGE in public/house-plot.js),
// so a new piece that meets her roof is placed by the roof's ridge, not by B (the double chimney's stack, below).
const PEN = Object.freeze({ L: [4.5, 195], A: [178 / 16, 55 / 16], B: [115 / 16, -83 / 16], Z: 13, wall: 9.5, ridge: 16 });
const proj = ([a, b, z], [ox, oy] = [0, 0]) => [PEN.L[0] + a * PEN.A[0] + b * PEN.B[0] + ox, PEN.L[1] + a * PEN.A[1] + b * PEN.B[1] - z * PEN.Z + oy];
const sub2 = (p, q) => [p[0] - q[0], p[1] - q[1]];
const add3 = (p, q) => [p[0] + q[0], p[1] + q[1], p[2] + q[2]];
const mul3 = (p, s) => [p[0] * s, p[1] * s, p[2] * s];

/**
 * Her materials, each a parallelogram of her sheet: `q0` its corner (sheet pixels), `u` the way the grain runs and `v`
 * across it, and how many feet each covers when laid on a new face at about her own pixel scale. Read on grids of her
 * frames (three times size, ten-pixel lines).
 */
const TEXTURES = (() => {
  const at = (name, [x, y]) => { const f = her(name); return [f.x + x, f.y + y]; };
  const t = (name, q0, u, v, feetU, feetV) => ({ href: her(name).href, sheetW: her(name).sheetW, sheetH: her(name).sheetH, q0: at(name, q0), u, v, feetU, feetV });
  return {
    // Bark-on logs from the door's face of her round walls, left of the door: the logs run along u.
    roundLogs: t('house-round-full-walls', [30, 96], [36, 11], [0, 96], 3.2, 7.4),
    hewnLogs: t('house-hewn-full-walls', [28, 98], [36, 12], [0, 100], 3.2, 7.7),
    // Planks of her passage floor's deck, running along u.
    planks: t('house-passage-floor', [14, 66], [100, -60], [124, 27], 12, 12),
    // Upright boards of her shed room's front, left of the door: the boards run down u.
    boards: t('house-shed-room', [52, 76], [0, 70], [96, 32], 5.4, 8.4),
    // Clapboards of her finished roof's right slope, running down the slope along u, the weight poles across them.
    roof: t('house-hewn-roof-finished', [150, 86], [74, 94], [54, -45], 10, 6),
    // A round post of her porch, running down u.
    post: t('house-porch', [165.5, 100], [0, 84], [8, 0], 7, 0.9),
    // Laid stone from the fire-box of her stone chimney.
    stone: t('house-chimney-stone', [20, 164], [48, 0], [0, 60], 4.2, 4.6),
    // Clay and sticks from her stick-and-mud chimney.
    mud: t('house-chimney-stick', [46, 92], [42, 0], [0, 80], 3.6, 6),
    // The jacal's woven sticks, its daub and its thatch (houses-settling).
    wattle: t('house-jacal-walls', [35, 56], [64, 0], [0, 46], 5.5, 4),
    daub: t('house-jacal', [36, 94], [58, 0], [0, 48], 5, 4.2),
    thatch: t('house-jacal', [62, 20], [0, 40], [160, 0], 4.5, 14),
  };
})();

/** The SVG affine matrix taking source vectors (su, sv) at q0 to screen vectors (pu, pv) at p0. */
function affine(q0, su, sv, p0, pu, pv) {
  const det = su[0] * sv[1] - su[1] * sv[0];
  const inv = [[sv[1] / det, -sv[0] / det], [-su[1] / det, su[0] / det]]; // rows of [su sv]^-1
  const a = pu[0] * inv[0][0] + pv[0] * inv[1][0], c = pu[0] * inv[0][1] + pv[0] * inv[1][1];
  const b = pu[1] * inv[0][0] + pv[1] * inv[1][0], d = pu[1] * inv[0][1] + pv[1] * inv[1][1];
  return [a, b, c, d, p0[0] - (a * q0[0] + c * q0[1]), p0[1] - (b * q0[0] + d * q0[1])];
}

/**
 * A modeller for one frame: faces in feet, laid with her materials and outlined in her ink. `offset` moves the projection
 * in the frame; `shade` darkens a face turned away from the light (her pens: the door's face lit, the long side darker).
 */
class Model {
  constructor(name, w, h, offset) { this.c = new Canvas(name, w, h); this.offset = offset; }
  /** A point in feet to pixels; a fourth number moves it that many pixels across (the stack set on her ridge). */
  p(pt) { const q = proj(pt, this.offset); if (pt.length > 3) q[0] += pt[3]; return q; }
  /**
   * A flat face: `corners` in feet (any polygon on one plane), laid with `texture` whose grain runs along `u3` and across
   * along `v3` (unit directions in feet) from `origin3`.
   */
  face(corners, texture, { origin3 = corners[0], u3, v3, shade = 0, outline = LINE.inner, tint } = {}) {
    const c = this.c, poly = corners.map(q => this.p(q));
    const clip = c.clip(poly);
    const tex = TEXTURES[texture];
    const o = this.p(origin3);
    const pu = sub2(this.p(add3(origin3, mul3(u3, tex.feetU))), o), pv = sub2(this.p(add3(origin3, mul3(v3, tex.feetV))), o);
    // How many tiles each way cover the face: the face's extent in the (u, v) grid.
    const det = pu[0] * pv[1] - pu[1] * pv[0];
    const uv = poly.map(([x, y]) => { const dx = x - o[0], dy = y - o[1]; return [(dx * pv[1] - dy * pv[0]) / det, (pu[0] * dy - pu[1] * dx) / det]; });
    const [i0, i1] = [Math.floor(Math.min(...uv.map(q => q[0]))), Math.ceil(Math.max(...uv.map(q => q[0])))];
    const [j0, j1] = [Math.floor(Math.min(...uv.map(q => q[1]))), Math.ceil(Math.max(...uv.map(q => q[1])))];
    const src = c.id('src');
    c.defs.push(`<clipPath id="${src}"><polygon points="${P([tex.q0, [tex.q0[0] + tex.u[0], tex.q0[1] + tex.u[1]], [tex.q0[0] + tex.u[0] + tex.v[0], tex.q0[1] + tex.u[1] + tex.v[1]], [tex.q0[0] + tex.v[0], tex.q0[1] + tex.v[1]]])}"/></clipPath>`);
    const tiles = [];
    for (let i = i0; i < i1; i++) for (let j = j0; j < j1; j++) {
      // A little over one tile each way, so the soft edge of a tile never lets ground show between tiles.
      const p0 = [o[0] + (i - 0.02) * pu[0] + (j - 0.02) * pv[0], o[1] + (i - 0.02) * pu[1] + (j - 0.02) * pv[1]];
      const m = affine(tex.q0, tex.u, tex.v, p0, pu.map(x => x * 1.04), pv.map(x => x * 1.04));
      tiles.push(`<g transform="matrix(${m.map(f2).join(' ')})"><g clip-path="url(#${src})"><image href="${tex.href}" x="0" y="0" width="${tex.sheetW}" height="${tex.sheetH}"/></g></g>`);
    }
    c.raw(`<g clip-path="url(#${clip})">${tiles.join('')}${tint ? `<polygon points="${P(poly)}" fill="${tint[0]}" opacity="${tint[1]}"/>` : ''}${shade ? `<polygon points="${P(poly)}" fill="#2a1a0c" opacity="${shade}"/>` : ''}</g>`);
    if (outline) c.raw(`<polygon points="${P(poly)}" fill="none" stroke="${INK}" stroke-width="${outline}" stroke-linejoin="round"/>`);
    return poly;
  }
  /** A box's three faces the camera sees (-b, +a, top), each laid with its material. */
  box([a0, b0, z0], [a1, b1, z1], texture, { top = texture, grain = 'b', shade = 0.2, topGrain = grain, tint } = {}) {
    const along = grain === 'a' ? [1, 0, 0] : grain === 'z' ? [0, 0, -1] : [0, 1, 0];
    // The face toward the lower left (b = b0): logs or boards run along a on it, or up it.
    this.face([[a0, b0, z0], [a1, b0, z0], [a1, b0, z1], [a0, b0, z1]], texture, { origin3: [a0, b0, z1], u3: grain === 'z' ? [0, 0, -1] : [1, 0, 0], v3: grain === 'z' ? [1, 0, 0] : [0, 0, -1], tint });
    // The face toward the lower right (a = a1), in shade.
    this.face([[a1, b0, z0], [a1, b1, z0], [a1, b1, z1], [a1, b0, z1]], texture, { origin3: [a1, b0, z1], u3: grain === 'z' ? [0, 0, -1] : [0, 1, 0], v3: grain === 'z' ? [0, 1, 0] : [0, 0, -1], shade, tint });
    // The top.
    const tu = topGrain === 'a' ? [1, 0, 0] : [0, 1, 0], tv = topGrain === 'a' ? [0, 1, 0] : [1, 0, 0];
    this.face([[a0, b0, z1], [a1, b0, z1], [a1, b1, z1], [a0, b1, z1]], top, { origin3: [a0, b0, z1], u3: tu, v3: tv, tint });
    void along;
  }
  /** An upright round post from z0 to z1 at (a, b), `r` feet thick: a lit front, a shaded side, a cut top. */
  post([a, b], z0, z1, r = 0.45) {
    const c = this.c, bottom = this.p([a, b, z0]), top = this.p([a, b, z1]), w = r * 2 * 11;
    const poly = [[top[0] - w / 2, top[1]], [top[0] + w / 2, top[1]], [bottom[0] + w / 2, bottom[1]], [bottom[0] - w / 2, bottom[1]]];
    const clip = c.clip(poly), tex = TEXTURES.post;
    const m = affine(tex.q0, tex.u, tex.v, poly[0], [0, bottom[1] - top[1]], [w, 0]);
    c.raw(`<g clip-path="url(#${clip})"><g transform="matrix(${m.map(f2).join(' ')})"><image href="${tex.href}" x="0" y="0" width="${tex.sheetW}" height="${tex.sheetH}"/></g></g>`);
    c.raw(`<polygon points="${P(poly)}" fill="none" stroke="${INK}" stroke-width="${LINE.inner}" stroke-linejoin="round"/>`);
    c.raw(`<ellipse cx="${f2(top[0])}" cy="${f2(top[1])}" rx="${f2(w / 2)}" ry="${f2(w / 4)}" fill="#c89a5c" stroke="${INK}" stroke-width="${LINE.fine}"/>`);
  }
  /** A beam from p to q (feet), `r` feet thick, drawn as a round pole in her post's wood. */
  beam(p3, q3, r = 0.35) {
    const c = this.c, p = this.p(p3), q = this.p(q3), d = sub2(q, p), l = Math.hypot(...d), n = [-d[1] / l * r * 11, d[0] / l * r * 11];
    const poly = [[p[0] + n[0], p[1] + n[1]], [q[0] + n[0], q[1] + n[1]], [q[0] - n[0], q[1] - n[1]], [p[0] - n[0], p[1] - n[1]]];
    const clip = c.clip(poly), tex = TEXTURES.post;
    const m = affine(tex.q0, tex.u, tex.v, poly[0], sub2(poly[1], poly[0]), sub2(poly[3], poly[0]));
    c.raw(`<g clip-path="url(#${clip})"><g transform="matrix(${m.map(f2).join(' ')})"><image href="${tex.href}" x="0" y="0" width="${tex.sheetW}" height="${tex.sheetH}"/></g></g>`);
    c.raw(`<polygon points="${P(poly)}" fill="none" stroke="${INK}" stroke-width="${LINE.fine + 0.4}" stroke-linejoin="round"/>`);
  }
  /** A dark opening (a door, a flue, a loophole) on a face. */
  hole(corners, fill = '#2b1c12') { const poly = corners.map(q => this.p(q)); this.c.raw(`<polygon points="${P(poly)}" fill="${fill}" stroke="${INK}" stroke-width="${LINE.fine + 0.4}" stroke-linejoin="round"/>`); return poly; }
  svg(note) { return this.c.svg(note); }
}

