/** Put a frame drawn in its own w x h box at the top left of a larger cell, and move its fractions to the cell. */
function padTo(drawn, cell) {
  const m = drawn.svg.match(/viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"/);
  const w = +m[1], h = +m[2];
  if (w === cell.w && h === cell.h) return drawn;
  if (w > cell.w || h > cell.h) throw new Error(`house-pieces: a ${w}x${h} frame does not fit its ${cell.w}x${cell.h} cell`);
  // Anchored at the bottom of the cell so the ground sits low, centred across.
  const ox = Math.round((cell.w - w) / 2), oy = cell.h - h;
  const fx = x => +((ox + x * w) / cell.w).toFixed(4), fy = y => +((oy + y * h) / cell.h).toFixed(4);
  const svg = drawn.svg.replace(`width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"`, `width="${cell.w}" height="${cell.h}" viewBox="0 0 ${cell.w} ${cell.h}"`)
    .replace(/<g>/, `<g transform="translate(${ox} ${oy})">`)
    .replace(/<defs>/, `<defs>`);
  // clipPaths are in user space of the element they apply to: they sit inside the translated group, so they move with it.
  const out = { ...drawn, svg, anchorX: fx(drawn.anchorX), anchorY: fy(drawn.anchorY),
    // The picture keeps its pixel scale: the logical height is still that of the frame of hers it goes with.
    logicalHeight: drawn.logicalHeight };
  if (drawn.seat) out.seat = [fx(drawn.seat[0]), fy(drawn.seat[1])];
  if (drawn.ground) out.ground = Object.fromEntries(Object.entries(drawn.ground).map(([k, [x, y]]) => [k, [fx(x), fy(y)]]));
  if (drawn.extra?.ridge) out.extra = { ...drawn.extra, ridge: drawn.extra.ridge.map(([x, y]) => [fx(x), fy(y)]) };
  return out;
}
