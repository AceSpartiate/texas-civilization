/** A frame fitted round a piece: its corners in feet, room round them, and its ground anchor as a point in feet. */
function fitted(name, corners, anchor3, pad = 8) {
  const pts = corners.map(q => proj(q));
  const x0 = Math.min(...pts.map(p => p[0])), x1 = Math.max(...pts.map(p => p[0])), y0 = Math.min(...pts.map(p => p[1])), y1 = Math.max(...pts.map(p => p[1]));
  const m = new Model(name, Math.ceil(x1 - x0 + 2 * pad), Math.ceil(y1 - y0 + 2 * pad), [pad - x0, pad - y0]);
  const [ax, ay] = m.p(anchor3);
  return { m, anchorX: +(ax / m.c.w).toFixed(4), anchorY: +(ay / m.c.h).toFixed(4) };
}
const boxCorners = ([a0, b0, z0], [a1, b1, z1]) => [[a0, b0, z0], [a1, b0, z0], [a1, b1, z0], [a0, b1, z0], [a0, b0, z1], [a1, b0, z1], [a1, b1, z1], [a0, b1, z1]];

