// ---------------------------------------------------------------------------------------------------------------- E4: the jacal
// A jacal pen in the log pens' own projection and footprint, so it goes up by stages as they do and seats its roof the same
// way: posts set upright in a trench (`house-jacal-posts`), the walls woven with sticks between them and daubed with mud
// (`house-jacal-wattle`), and a thatched roof, hipped as her whole jacal's is (`house-jacal-thatch`). Laid with her own
// daub, wattle, posts and thatch from the houses-settling jacal. Research: HIST-GONZ notes a jacal as "posts set in the
// ground, walls of sticks and mud between, a roof of thatch" (sim/houseplot.mjs); Texas jacales were commonly of upright
// posts or pickets set in a trench and chinked or plastered with mud, roofed with thatch or tule. Wall height and pitch are
// read from her jacal and are not a documented measurement.
const JACAL = { wall: 7.5, door: [6.6, 10.4], doorHigh: 6.2, posts: [0, 4, 8, 12, 16], wallPosts: [0, 8, 16] };

function jacalPosts({ m }, { upTo = JACAL.wall, daub = false } = {}) {
  const { wall } = JACAL, every = daub ? JACAL.wallPosts : JACAL.posts;
  // Far walls first (their inner faces), then the near walls; posts at every four feet and at the door.
  const far = [...every.map(b => [0, b]), ...every.slice(1).map(a => [a, 16])];
  const near = [...every.map(a => [a, 0]).filter(([a]) => a < 16), ...every.map(b => [16, b])];
  if (!daub) {
    // The trench the posts are set in, dug round the square: turned earth.
    const trench = [[0, 0, 0], [16, 0, 0], [16, 16, 0], [0, 16, 0]].map(q => m.p(q));
    m.c.raw(`<polygon points="${P(trench)}" fill="none" stroke="${INK}" stroke-width="9" stroke-linejoin="round" opacity="0.8"/><polygon points="${P(trench)}" fill="none" stroke="#8a5f38" stroke-width="6" stroke-linejoin="round"/><polygon points="${P(trench)}" fill="none" stroke="#5e3f22" stroke-width="2" stroke-linejoin="round" stroke-dasharray="3 5"/>`);
  }
  if (daub) {
    // The far walls' inner faces: the a = 0 wall seen from inside (toward +a, in shade) and the b = 16 wall (toward -b).
    m.face([[0, 0, 0], [0, 16, 0], [0, 16, wall], [0, 0, wall]], 'daub', { origin3: [0, 0, wall], u3: [0, 1, 0], v3: [0, 0, -1], shade: 0.3 });
    m.face([[0, 16, 0], [16, 16, 0], [16, 16, wall], [0, 16, wall]], 'daub', { origin3: [0, 16, wall], u3: [1, 0, 0], v3: [0, 0, -1], shade: 0.12 });
  }
  for (const [a, b] of far.sort((p, q) => q[1] - p[1] || p[0] - q[0])) m.post([a, b], 0, upTo + 0.3, 0.55);
  if (daub) {
    const [d0, d1] = JACAL.door;
    // The door's face, with the doorway cut through it, and the long side with a small window.
    m.face([[0, 0, 0], [d0, 0, 0], [d0, 0, JACAL.doorHigh], [d1, 0, JACAL.doorHigh], [d1, 0, 0], [16, 0, 0], [16, 0, wall], [0, 0, wall]], 'daub', { origin3: [0, 0, wall], u3: [1, 0, 0], v3: [0, 0, -1] });
    m.hole([[d0, 0, 0], [d1, 0, 0], [d1, 0, JACAL.doorHigh], [d0, 0, JACAL.doorHigh]], '#3a2616');
    m.face([[16, 0, 0], [16, 16, 0], [16, 16, wall], [16, 0, wall]], 'daub', { origin3: [16, 0, wall], u3: [0, 1, 0], v3: [0, 0, -1], shade: 0.22 });
    m.hole([[16, 9, 3.6], [16, 11.5, 3.6], [16, 11.5, 5.4], [16, 9, 5.4]], '#2b1c12');
    // The wall plate along the tops.
    m.beam([0, 0, wall], [16, 0, wall], 0.3); m.beam([16, 0, wall], [16, 16, wall], 0.3);
  }
  const inDoor = ([a, b]) => b === 0 && a > JACAL.door[0] && a < JACAL.door[1];
  const nearPosts = [...near.filter(post => !inDoor(post)), [JACAL.door[0], 0], [JACAL.door[1], 0]].sort((p, q) => q[1] - p[1] || p[0] - q[0]);
  for (const [a, b] of nearPosts) m.post([a, b], 0, upTo + 0.3, 0.55);
  if (daub) m.beam([JACAL.door[0], 0, JACAL.doorHigh], [JACAL.door[1], 0, JACAL.doorHigh], 0.28);
}

